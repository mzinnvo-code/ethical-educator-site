export function normalizeIsbn(isbn) {
  return String(isbn).replace(/[^0-9X]/gi, "").toUpperCase();
}

export function openLibraryCover(isbn, size = "M") {
  return `https://covers.openlibrary.org/b/ISBN/${normalizeIsbn(isbn)}-${size}.jpg?default=false`;
}

export function openLibraryCoverById(id, size = "M") {
  return `https://covers.openlibrary.org/b/id/${id}-${size}.jpg?default=false`;
}

export function openLibraryBookUrl(isbn) {
  return `https://openlibrary.org/isbn/${normalizeIsbn(isbn)}`;
}

