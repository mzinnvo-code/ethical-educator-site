export function getResourcesForCategory(categoryId, filterId = "all") {
  const items = categoryItems[categoryId] || [];
  if (filterId === "all") return items;
  return items.filter((item) => item.tags?.includes(filterId));
}

export function getCategoryCount(categoryId, filterId = "all") {
  return getResourcesForCategory(categoryId, filterId).length;
}
