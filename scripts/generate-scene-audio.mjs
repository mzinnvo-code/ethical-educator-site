#!/usr/bin/env node
// Generate ElevenLabs voice-overs for K-5 scene-based scenarios — currently
// just "Explaining Red" K-2. Sibling to scripts/generate-k5-audio.mjs but
// supports per-chunk voice ids (the scene has 4 distinct character voices).
//
// Usage:
//   npm run audio:scene                         # generate everything (incremental)
//   npm run audio:scene -- --dry-run            # plan only, no API calls
//   npm run audio:scene -- --scenario=explaining-red-k-2
//   npm run audio:scene -- --slot=intro,beat1-ada    # generate just these slots
//   npm run audio:scene -- --force              # ignore cache
//
// Required env (load via `node --env-file=.env.local ...` — wired in package.json):
//   ELEVENLABS_API_KEY    your ElevenLabs API key

import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import {
  EXPLAINING_RED_K2_AUDIO,
  SCENE_VOICES,
  SCENARIO_ID as EXPLAINING_RED_K2_ID,
} from "../src/data/explainingRedK2Audio.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(__dirname, "..");
const MANIFEST_PATH = resolve(REPO, "src/data/k5AudioManifest.json");
const PUBLIC_AUDIO_DIR = resolve(REPO, "public/audio/k5");

// ──────────────── Config ────────────────
const MODEL_ID = "eleven_v3";
const OUTPUT_FORMAT = "mp3_44100_128";
const API_BASE = "https://api.elevenlabs.io/v1/text-to-speech";

// Catalog of all scene-based scenarios that this generator covers.
const SCENE_SCENARIOS = {
  [EXPLAINING_RED_K2_ID]: {
    chunks: EXPLAINING_RED_K2_AUDIO,
    voices: SCENE_VOICES,
  },
};

// ──────────────── CLI ────────────────
function parseArgs(argv) {
  const args = { dryRun: false, force: false, scenario: null, slots: null };
  for (const a of argv.slice(2)) {
    if (a === "--dry-run") args.dryRun = true;
    else if (a === "--force") args.force = true;
    else if (a.startsWith("--scenario=")) args.scenario = a.slice("--scenario=".length);
    else if (a.startsWith("--slot=")) args.slots = a.slice("--slot=".length).split(",").filter(Boolean);
    else if (a === "--help" || a === "-h") {
      console.log("Usage: node scripts/generate-scene-audio.mjs [--dry-run] [--scenario=<id>] [--slot=<a,b,c>] [--force]");
      process.exit(0);
    }
    else {
      console.error(`Unknown flag: ${a}`);
      process.exit(2);
    }
  }
  return args;
}

// ──────────────── Manifest ────────────────
async function loadManifest() {
  if (!existsSync(MANIFEST_PATH)) {
    return {
      _note: "Generated by scripts/generate-k5-audio.mjs. Do not edit by hand.",
      voiceId: null,
      modelId: null,
      voiceSettings: null,
      scenarios: {},
    };
  }
  return JSON.parse(await readFile(MANIFEST_PATH, "utf8"));
}

async function saveManifest(manifest) {
  // The k5-audio generator writes voiceId/modelId/voiceSettings as top-level
  // metadata for its single-voice catalog. Don't clobber those here — scene
  // chunks carry their own per-voice metadata in the per-chunk entries.
  await writeFile(MANIFEST_PATH, JSON.stringify(manifest, null, 2) + "\n", "utf8");
}

// ──────────────── Hashing ────────────────
function hashChunk({ voiceId, stability, toneText }) {
  // Hash everything that affects the produced audio. Per-chunk voice and
  // stability so each speaker invalidates independently when tuned.
  const settingsKey = JSON.stringify({ stability });
  return createHash("sha256")
    .update(`${voiceId}|${MODEL_ID}|${settingsKey}|${toneText}`)
    .digest("hex")
    .slice(0, 16);
}

// ──────────────── ElevenLabs API ────────────────
function stripEmphasis(text) {
  // Strip markdown-style emphasis (*foo* / _foo_) before TTS so the voice
  // doesn't read literal asterisks. Mirrors the same helper in
  // generate-k5-audio.mjs so the two generators behave identically.
  return text
    .replace(/\*([^*\n]+)\*/g, "$1")
    .replace(/(^|\s)_([^_\n]+)_(?=\s|[.,;:!?]|$)/g, "$1$2");
}

async function elevenlabsTTS({ voiceId, stability, toneText }) {
  const apiKey = process.env.ELEVENLABS_API_KEY;
  if (!apiKey) throw new Error("ELEVENLABS_API_KEY is not set. Add it to .env.local.");

  const url = `${API_BASE}/${voiceId}?output_format=${OUTPUT_FORMAT}`;
  const body = JSON.stringify({
    text: toneText,
    model_id: MODEL_ID,
    voice_settings: { stability },
  });

  const delays = [2000, 4000, 8000];
  for (let attempt = 0; attempt <= delays.length; attempt++) {
    let res;
    try {
      res = await fetch(url, {
        method: "POST",
        headers: {
          "xi-api-key": apiKey,
          "Content-Type": "application/json",
          "Accept": "audio/mpeg",
        },
        body,
      });
    } catch (err) {
      if (attempt === delays.length) throw err;
      console.warn(`  network error: ${err.message} — retrying in ${delays[attempt]}ms`);
      await new Promise(r => setTimeout(r, delays[attempt]));
      continue;
    }

    if (res.ok) {
      return Buffer.from(await res.arrayBuffer());
    }

    if (res.status === 401) {
      const detail = await res.text().catch(() => "");
      if (detail.includes("quota_exceeded")) {
        throw new Error(`ElevenLabs quota exceeded for this billing period. Upgrade plan or wait for monthly reset. ${detail}`);
      }
      throw new Error(`ElevenLabs 401 unauthorized — check ELEVENLABS_API_KEY. ${detail}`);
    }
    if (res.status === 422) {
      const detail = await res.text().catch(() => "");
      throw new Error(`ElevenLabs 422 unprocessable — likely bad voice/model id or text. voice=${voiceId}. ${detail}`);
    }
    if (res.status >= 500 || res.status === 429) {
      if (attempt === delays.length) {
        const detail = await res.text().catch(() => "");
        throw new Error(`ElevenLabs ${res.status} after ${delays.length + 1} attempts: ${detail}`);
      }
      const delay = res.status === 429 ? Math.max(delays[attempt], 30000) : delays[attempt];
      console.warn(`  ${res.status} — retrying in ${delay}ms`);
      await new Promise(r => setTimeout(r, delay));
      continue;
    }
    const detail = await res.text().catch(() => "");
    throw new Error(`ElevenLabs ${res.status}: ${detail}`);
  }
  throw new Error("unreachable");
}

// ──────────────── Walk scenarios ────────────────
function* enumerateChunks(scenarios, args) {
  for (const [scenarioId, scenario] of Object.entries(scenarios)) {
    if (args.scenario && args.scenario !== scenarioId) continue;
    for (const chunk of scenario.chunks) {
      if (args.slots && !args.slots.includes(chunk.slot)) continue;
      const voice = scenario.voices[chunk.speaker];
      if (!voice) {
        console.warn(`  no voice mapped for speaker "${chunk.speaker}" in ${scenarioId}/${chunk.slot} — skipping`);
        continue;
      }
      const toneText = stripEmphasis(`${chunk.tag} ${chunk.text}`);
      yield {
        scenarioId,
        slot: chunk.slot,
        speaker: chunk.speaker,
        voiceId: voice.voiceId,
        stability: voice.stability,
        toneText,
        plainText: chunk.text,
      };
    }
  }
}

// ──────────────── Main ────────────────
async function main() {
  const args = parseArgs(process.argv);

  console.log(`Scene audio generation`);
  console.log(`  model:    ${MODEL_ID}`);
  if (args.dryRun) console.log(`  mode:     DRY RUN — no API calls, no file writes`);
  if (args.force) console.log(`  mode:     FORCE — ignoring cache`);
  if (args.scenario) console.log(`  scenario: ${args.scenario}`);
  if (args.slots) console.log(`  slots:    ${args.slots.join(", ")}`);
  console.log("");

  const manifest = await loadManifest();
  manifest.scenarios = manifest.scenarios || {};

  if (args.scenario && !SCENE_SCENARIOS[args.scenario]) {
    console.error(`Unknown scene scenario: ${args.scenario}`);
    console.error(`Known: ${Object.keys(SCENE_SCENARIOS).join(", ")}`);
    process.exit(1);
  }

  const planned = [];
  for (const chunk of enumerateChunks(SCENE_SCENARIOS, args)) {
    planned.push(chunk);
  }

  console.log(`Planned ${planned.length} chunk(s).\n`);

  let generated = 0, skipped = 0, totalChars = 0;

  for (const chunk of planned) {
    const { scenarioId, slot, speaker, voiceId, stability, toneText, plainText } = chunk;
    const hash = hashChunk({ voiceId, stability, toneText });
    const existing = manifest.scenarios[scenarioId]?.[slot];
    const cached = !args.force
      && existing?.hash === hash
      && existsSync(resolve(REPO, "public" + existing.file));

    if (cached) {
      skipped++;
      if (args.dryRun) console.log(`  [skip ] ${scenarioId}/${slot} (${speaker}, ${plainText.length}c)`);
      continue;
    }

    if (args.dryRun) {
      console.log(`  [plan ] ${scenarioId}/${slot} (${speaker}, ${plainText.length}c) :: "${toneText.slice(0, 80)}${toneText.length > 80 ? "…" : ""}"`);
      generated++;
      totalChars += toneText.length;
      continue;
    }

    const dir = resolve(PUBLIC_AUDIO_DIR, scenarioId);
    await mkdir(dir, { recursive: true });
    const file = resolve(dir, `${slot}.mp3`);

    process.stdout.write(`  [gen  ] ${scenarioId}/${slot} (${speaker}, ${plainText.length}c) ... `);
    try {
      const buf = await elevenlabsTTS({ voiceId, stability, toneText });
      await writeFile(file, buf);
      manifest.scenarios[scenarioId] = manifest.scenarios[scenarioId] || {};
      manifest.scenarios[scenarioId][slot] = {
        file: `/audio/k5/${scenarioId}/${slot}.mp3`,
        hash,
        chars: plainText.length,
        bytes: buf.length,
        speaker,
        voiceId,
      };
      await saveManifest(manifest);
      generated++;
      totalChars += toneText.length;
      console.log(`ok (${(buf.length / 1024).toFixed(1)} KB)`);
    } catch (err) {
      console.log(`FAILED`);
      console.error(`    ${err.message}`);
      throw err;
    }
  }

  console.log("");
  console.log(`Done. Generated: ${generated}  Skipped (cached): ${skipped}  Chars: ${totalChars}`);
  if (!args.dryRun) {
    const cost = (totalChars / 1000) * 0.15;  // Rough v3 estimate (~$0.15/1k chars)
    console.log(`Approx. ElevenLabs cost: ~$${cost.toFixed(2)} (estimate, varies by plan)`);
    console.log(`Manifest written to ${MANIFEST_PATH}`);
  }
}

const isCLI = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isCLI) {
  main().catch(err => {
    console.error(`\nFATAL: ${err.message}`);
    process.exit(1);
  });
}
